// 記事「40歳で十勝に帰って、95歳まで」(content/posts/lifeplan-one-line-95.md)
// の全数値はこのスクリプトで計算した。記事は「毎年の資産公開で答え合わせして
// いく」と締めているので、年に1回（月次の資産公開が出たあと）これを回して、
// 線がどれだけずれたかを見る。
//
// 【毎年更新するのはこの2つだけ】
//   現在年齢 … 誕生日は3月7日。3月の答え合わせなら +1 する
//   現在資産 … 最新の monthly-report の総資産
//
// 【前提の出どころ】数字を変えるときは元記事との整合を確認すること
//   実家月12.5万   → tokachi-plan-03-money-simulation（10万弱＋社会保険2〜3万）
//   iDeCo 1,285万  → ideco-restart-minimum（再開シナリオ・60歳・税0円）
//   年金 実質月7万 → freelance-pension-future の月9万に、2024年財政検証
//                    （過去30年投影ケース）の基礎年金3割減を掛けたもの。
//                    物価スライド前提なので「実質で一定」として扱う
//   運用 名目5%    → 全世界株ドル建て実績9%から円安分と現金・日本株の
//                    混在を引いた控えめ値。財政検証の下から2番目相当
//
// 【モデルの決めごと】
//   ・帰郷年齢までは働いて生活費は収入でまかなう。資産は名目5%で回り
//     （取り崩さないので課税は実現しない）、年160万円を追加する
//   ・帰郷後は取り崩し期。運用は税引き後4%（名目）
//   ・旅行・生活費・ゆる収入は物価連動、iDeCo掛金(月5,000円)は名目固定
//   ・表示はすべて「いまの物価」に直した実質値（名目÷1.02^経過年）
//   ・運用は毎年一定。取り崩し初期の暴落（順序リスク）は表現できない。
//     これはモデルの限界として記事にも書いてある
// ═══════════════════════════════════════════════════════════════════

// ══ 毎年更新する場所 ══════════════════════════════════════════════
const 現在年齢 = 34;
const 現在資産 = 58_310_000;   // monthly-report-2026-07
// ═══════════════════════════════════════════════════════════════════

const 帰郷年齢 = 40;            // 節目としての仮置き（十勝計画②：決めてはいない）
const 積立年   = 1_600_000;     // つみたて月5万＋年100万
const 実家月   = 125_000;
const 旅行基準 = 1_000_000;
const iDeCo60  = 12_850_000;
const iDeCo掛金 = 60_000;       // 月5,000円（帰郷後〜59歳は資産から払う）
const 年金実質月 = 70_000;      // 月9万×マクロ経済スライド3割減(基礎部分)≒7万

const y = n => Math.round(n).toLocaleString("ja-JP");
const man = n => y(n / 10_000) + "万";

function sim({ infl = 0.02, ret = 0.04, 住居月 = 実家月, 旅行 = 旅行基準,
               ゆる月 = 0, 年金月 = 年金実質月, 施設 = null } = {}) {
  let a = 現在資産, snap = {}, 尽きる = null;
  for (let age = 現在年齢; age < 帰郷年齢; age++) a = a * 1.05 + 積立年;
  const 帰郷時名目 = a;
  for (let age = 帰郷年齢; age <= 95; age++) {
    const 物価 = Math.pow(1 + infl, age - 現在年齢);
    const 住 = (施設 && age >= 施設.from) ? 施設.月 : 住居月;
    const 支出 = 住 * 12 * 物価 + 旅行 * 物価 + (age < 60 ? iDeCo掛金 : 0);
    const 収入 = (age < 65 ? ゆる月 * 12 * 物価 : 0) + (age >= 65 ? 年金月 * 12 * 物価 : 0);
    a = a * (1 + ret) - Math.max(0, 支出 - 収入);
    if (age === 60) a += iDeCo60;
    if (a < 0 && !尽きる) 尽きる = age;
    snap[age] = a / 物価;
  }
  return { 帰郷時名目, snap, 尽きる };
}

const AGES = [帰郷年齢, 60, 75, 85, 95];
const res = r => r.尽きる ? `❌ ${r.尽きる}歳で尽きる` : `✓ 95歳で ${man(r.snap[95])}`;

console.log(`═══ ${現在年齢}歳・${man(現在資産)}円からの答え合わせ ═══`);
{
  const r = sim({});
  const 物価 = Math.pow(1.02, 帰郷年齢 - 現在年齢);
  console.log(`\n① ${帰郷年齢}歳時点: 名目 ${man(r.帰郷時名目)} ／ いまの物価で ${man(r.帰郷時名目 / 物価)}`);
  console.log(`   投資元本 ${man(積立年 * (帰郷年齢 - 現在年齢))} ／ 運用が増やすぶん ${man(r.帰郷時名目 - 現在資産 - 積立年 * (帰郷年齢 - 現在年齢))}`);
}
{
  const r = sim({ 旅行: 0 });
  console.log(`\n② 旅行なし・働かない: 95歳で ${man(r.snap[95])} ／ 取り崩し率 ${(実家月 * 12 / r.snap[帰郷年齢] * 100).toFixed(1)}%`);
}
console.log(`\n③ 旅行${man(旅行基準)}円・3通り（実質）`);
console.log("            " + AGES.map(a => (a + "歳").padStart(9)).join(""));
for (const [l, g] of [["月5万", 50_000], ["月3万", 30_000], ["働かない", 0]]) {
  const r = sim({ ゆる月: g });
  console.log(`  ${l.padEnd(8)}` + AGES.map(a => (r.snap[a] < 0 ? "枯渇" : man(r.snap[a])).padStart(9)).join("") + (r.尽きる ? ` ❌${r.尽きる}歳` : " ✓"));
}
console.log(`\n④ 旅行の上限`);
for (const t of [1_000_000, 1_300_000, 1_400_000, 1_500_000, 2_000_000])
  console.log(`  年${man(t).padStart(5)}  ${res(sim({ 旅行: t }))}`);
console.log(`\n⑤ 崩す（旅行${man(旅行基準)}円・働かない基準）`);
for (const [l, o] of [
  ["年金の目減りが深く 実質月6万", { 年金月: 60_000 }],
  ["80歳から施設 月25万", { 施設: { from: 80, 月: 250_000 } }],
  ["運用が税引き後3%", { ret: 0.03 }],
  ["実家に住めない（月17.5万）", { 住居月: 175_000 }],
  ["インフレ3%", { infl: 0.03 }],
  ["運用が税引き後2%", { ret: 0.02 }],
]) console.log(`  ${l.padEnd(26)} ${res(sim(o))}`);
console.log(`\n⑥ 重ねる`);
for (const [l, o] of [
  ["実家に住めない＋税引き後2%", { 住居月: 175_000, ret: 0.02 }],
  ["　＋ゆる収入 月5万", { 住居月: 175_000, ret: 0.02, ゆる月: 50_000 }],
  ["施設＋税引き後2%", { 施設: { from: 80, 月: 250_000 }, ret: 0.02 }],
]) console.log(`  ${l.padEnd(26)} ${res(sim(o))}`);
console.log(`\n⑦ 実家の効き目（税引き後2%）`);
{
  const A = sim({ 住居月: 175_000, ret: 0.02 }), B = sim({ ret: 0.02 }),
        C = sim({ 住居月: 175_000, ret: 0.02, ゆる月: 50_000 });
  const f = r => r.尽きる ? `${r.尽きる}歳で尽きる` : `95歳で ${man(r.snap[95])}`;
  console.log(`  一人暮らし・働かない ${f(A)} ／ 実家・働かない ${f(B)} ／ 一人暮らし＋月5万 ${f(C)}`);
}
